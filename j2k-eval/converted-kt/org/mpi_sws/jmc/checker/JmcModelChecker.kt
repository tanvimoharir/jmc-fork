package org.mpi_sws.jmc.checker

import org.apache.logging.log4j.LogManager
import org.apache.logging.log4j.Logger
import org.mpi_sws.jmc.checker.exceptions.JmcCheckerException
import org.mpi_sws.jmc.runtime.*
import org.mpi_sws.jmc.util.ExceptionUtil

/**
 * The JmcModelChecker class is responsible for managing the model checking process. It uses a
 * JmcCheckerConfiguration to configure the process and a JmcTestTarget to specify the program under
 * test.
 */
class JmcModelChecker
/**
 * Constructs a new JMC model checker with the given configuration.
 *
 * @param config the configuration to use
 */(private val config: JmcCheckerConfiguration) {
    /**
     * Checks the given test target. No instrumentation involved.
     *
     * @param target the test target to check
     * @return the report generated by the model checker
     */
    @Throws(JmcCheckerException::class)
    fun check(target: JmcTestTarget): JmcModelCheckerReport {
        val runtimeConfig = config.toRuntimeConfiguration()
        val report = JmcModelCheckerReport(runtimeConfig.reportPath)
        report.setupReportPath()
        val startTime = System.currentTimeMillis()
        var timeoutMarker = 0L
        if (config.timeout != null) {
            timeoutMarker = startTime + config.timeout.toMillis()
        }
        JmcRuntime.setup(runtimeConfig!!)
        var numIterations = config.numIterations
        var iteration = 0
        try {
            LOGGER.info("JMC checker started")
            while (true) {
                var successfulIteration = true
                try {
                    LOGGER.debug("Running iteration {}", iteration)
                    JmcRuntime.initIteration(iteration, report)
                    target.invoke()
                    val mainEndEvent =
                        JmcRuntimeEvent.Builder()
                            .type(JmcRuntimeEvent.Type.FINISH_EVENT)
                            .taskId(1L)
                            .build()
                    JmcRuntime.updateEvent(mainEndEvent)
                } catch (e: HaltTaskException) {
                    LOGGER.debug(
                        "Halting execution: {} due to main thread halted: {}",
                        iteration,
                        e.message
                    )
                } catch (e: HaltExecutionException) {
                    if (e.isReexecutionNeeded) {
                        // Since we are going to re-execute, do not count this iteration
                        numIterations++
                    } else {
                        report.errorIteration = iteration
                        report.errorMessage = e.message
                        LOGGER.error(
                            "Halting execution: {} due to exception: {}",
                            iteration,
                            e.message
                        )
                        throw e
                    }
                } catch (e: Exception) {
                    successfulIteration = false
                    // Catchall for any other exceptions that may occur
                    report.errorIteration = iteration
                    if (ExceptionUtil.isAssertionError(e)) {
                        report.errorMessage = String.format(
                            "Halting execution: %d due to assertion error: %s",
                            iteration, e.message
                        )
                        LOGGER.error(
                            "Assertion error in iteration {}: {}", iteration, e.message
                        )
                        JmcRuntime.recordTrace()
                        throw HaltCheckerException.Companion.error(
                            "Assertion error in iteration " + iteration + ": " + e.message,
                            e
                        )
                    } else {
                        throw e
                    }
                } finally {
                    JmcRuntime.resetIteration(iteration)
                    if (iteration % 50000 == 0) {
                        LOGGER.info("Completed {} iterations", iteration)
                        System.gc()
                    }
                    iteration++
                    if (numIterations != 0 && iteration >= numIterations && successfulIteration) {
                        throw HaltCheckerException.Companion.ok()
                    }
                    val curTime = System.currentTimeMillis()
                    if (timeoutMarker != 0L && curTime > timeoutMarker && successfulIteration) {
                        report.errorIteration = iteration
                        val errorMessage = String.format("Halting execution: %d due to timeout", iteration)
                        report.errorMessage = errorMessage
                        LOGGER.error(errorMessage)
                        throw HaltCheckerException.Companion.timeout()
                    }
                }
            }
        } catch (e: HaltCheckerException) {
            if (e.isOkay) {
                val totalIterations = iteration - 1
                report.totalIterations = totalIterations
                LOGGER.info("Model checking completed covering: {} iterations", totalIterations)
            } else if (e.isTimeout) {
                val totalIterations = iteration - 1
                report.totalIterations = totalIterations
                LOGGER.error("Model checker timeout out: {}", e.message)
            } else {
                report.errorIteration = -1
                report.errorMessage = String.format("Model checking failed: %s", e.message)
                LOGGER.error("Model checking failed: {}", e.message)
                if (e.cause != null) {
                    throw JmcCheckerException(e.message, e.cause)
                } else {
                    throw JmcCheckerException(e.message)
                }
            }
        } catch (e: Exception) {
            report.errorIteration = -1
            report.errorMessage = String.format(
                "Model checking failed with unexpected exception: %s", e.message
            )
            LOGGER.error("Model checking failed with unexpected exception: {}", e.message)
            if (e.cause != null) {
                throw JmcCheckerException(e.message, e.cause)
            } else {
                throw JmcCheckerException(e.message, e)
            }
        } finally {
            val endTime = System.nanoTime()
            JmcRuntime.tearDown(report)
            report.totalTimeMillis = endTime - startTime
            val totalIterations = report.totalIterations
            LOGGER.info(
                "Model checking explored: {} completed iterations", totalIterations -
                        report.blockedIterations
            )
            LOGGER.info("Model checking explored: {} blocked iterations", report.blockedIterations)
        }
        return report
    }

    /**
     * Replays the given test target. The replay is handled by the Strategy
     *
     * @param target the test target to replay
     * @throws JmcCheckerException if an error occurs during replay
     */
    @Throws(JmcCheckerException::class)
    fun replay(target: JmcTestTarget) {
        val runtimeConfig = config.toRuntimeConfiguration()
        JmcRuntime.setupReplay(runtimeConfig!!)
        val startTime = System.currentTimeMillis()

        val dummyReport =
            JmcModelCheckerReport(runtimeConfig.reportPath)
        try {
            JmcRuntime.initIteration(0, dummyReport)
            target.invoke()
            val mainEndEvent =
                JmcRuntimeEvent.Builder()
                    .type(JmcRuntimeEvent.Type.FINISH_EVENT)
                    .taskId(1L)
                    .build()
            JmcRuntime.updateEvent(mainEndEvent)
            JmcRuntime.resetIteration(0)
        } catch (e: HaltTaskException) {
            LOGGER.debug("Halting execution: due to main thread halted: {}", e.message)
        } catch (e: HaltExecutionException) {
            dummyReport.errorMessage = e.message
            LOGGER.error("Halting execution: due to exception: {}", e.message)
        } catch (e: AssertionError) {
            dummyReport.errorMessage = String.format("Halting execution due to assertion error: %s", e.message)
            LOGGER.error("Assertion error: {}", e.message)
        } catch (e: HaltCheckerException) {
            if (e.isOkay) {
                LOGGER.info("Replay completed successfully.")
            } else {
                dummyReport.errorIteration = -1
                dummyReport.errorMessage = String.format("Replaying failed: %s", e.message)
                LOGGER.error("Replaying failed: {}", e.message)
            }
        } finally {
            val endTime = System.currentTimeMillis()
            JmcRuntime.tearDown(dummyReport)
            dummyReport.totalTimeMillis = endTime - startTime
        }
    }

    companion object {
        private val LOGGER: Logger = LogManager.getLogger(
            JmcModelChecker::class.java
        )
    }
}
