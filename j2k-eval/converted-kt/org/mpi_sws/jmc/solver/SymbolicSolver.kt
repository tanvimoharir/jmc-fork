package org.mpi_sws.jmc.solver

import org.mpi_sws.jmc.api.symbolic.array.SymArrayVariable
import org.mpi_sws.jmc.api.symbolic.bool.JmcBooleanFormula
import org.mpi_sws.jmc.api.symbolic.bool.SymBoolVariable
import org.mpi_sws.jmc.api.symbolic.integer.SymIntVariable
import org.sosy_lab.common.ShutdownManager
import org.sosy_lab.common.configuration.Configuration
import org.sosy_lab.common.configuration.InvalidConfigurationException
import org.sosy_lab.common.log.BasicLogManager
import org.sosy_lab.common.log.LogManager
import org.sosy_lab.java_smt.SolverContextFactory
import org.sosy_lab.java_smt.SolverContextFactory.Solvers
import org.sosy_lab.java_smt.api.*

/**
 * The SymbolicSolver class is a core component designed for solving symbolic formulas within the program under the test.
 * It encapsulates the functionality for manipulating and solving symbolic representations of boolean and integer
 * variables. This class leverages the JavaSMT API to interface with various SMT (Satisfiability Modulo Theories) solvers,
 * providing a unified API for theorem proving tasks.
 *
 *
 * The class supports operations such as solving symbolic formulas, negating formulas, and creating dependency formulas
 * from a list of symbolic operations. It allows for the dynamic selection of SMT solvers based on the provided solver type,
 * enabling flexibility in choosing the underlying solver based on the specific requirements of the verification task.
 *
 *
 * SymbolicSolver initializes with a configuration, a logging manager, and a shutdown manager to handle the lifecycle
 * of the solver context. It provides methods to access and manipulate symbolic variables (both boolean and integer),
 * facilitating the creation of complex symbolic expressions that programmer can use.
 */
abstract class SymbolicSolver @JvmOverloads constructor(type: SMTSolverTypes = SMTSolverTypes.Z3) {
    /**
     * [.config] used to store the configuration settings for the solver context.
     */
    var config: Configuration? = null

    /**
     * [.logger] used to manage logging and output messages from the solver.
     */
    var logger: LogManager? = null

    /**
     * [.shutdown] used to manage the shutdown and cleanup of the solver context.
     */
    var shutdown: ShutdownManager? = null

    /**
     * [.symIntVariableMap] used to store the mapping of symbolic integer variables to their names.
     */
    var symIntVariableMap: MutableMap<String, SymIntVariable> = HashMap()

    /**
     * [.symBoolVariableMap] used to store the mapping of symbolic boolean variables to their names.
     */
    var symBoolVariableMap: MutableMap<String?, SymBoolVariable> = HashMap()

    /**
     * [.symArrayVariableMap] used to store the mapping of symbolic array variables to their names.
     */
    var symArrayVariableMap: Map<String, SymArrayVariable> = HashMap()

    /**
     * [.context] used to store the solver context for interacting with the SMT solver.
     */
    var context: SolverContext? = null
        protected set

    /**
     * [.fmgr] used to access the formula manager for creating and manipulating formulas.
     */
    var fmgr: FormulaManager? = null
        protected set

    /**
     * [.bmgr] used to access the boolean formula manager for boolean operations.
     */
    var bmgr: BooleanFormulaManager? = null
        protected set

    /**
     * [.imgr] used to access the integer formula manager for integer operations.
     */
    var imgr: IntegerFormulaManager? = null
        protected set

    /**
     * [.bmgr] used to access the array formula manager for array operations.
     */
    protected var amgr: ArrayFormulaManager? = null

    /**
     * [.model] used to store the model generated by the solver for a satisfiable formula.
     */
    var model: Model? = null
        protected set

    var isFreshProver: Boolean = true
        private set

    var solverTime: Long = 0L
        private set

    /**
     * Constructs a new instance of the SymbolicSolver class with the specified SMT solver type.
     *
     * @param type the type of SMT solver to use for solving symbolic formulas.
     */
    /**
     * Constructs a new instance of the SymbolicSolver class with the default SMT solver type (SMTInterpol).
     */
    init {
        val solverType = findSolverType(type)
        try {
            val startTime = System.nanoTime()
            config = Configuration.builder().build()
            logger = BasicLogManager.create(config)
            shutdown = ShutdownManager.create()
            context = SolverContextFactory.createSolverContext(
                config, logger, shutdown.getNotifier(), solverType
            )
            fmgr = context.getFormulaManager()
            bmgr = fmgr.getBooleanFormulaManager()
            imgr = fmgr.getIntegerFormulaManager()
            amgr = fmgr.getArrayFormulaManager()
            val endTime = System.nanoTime()
            advanceSolverTime(endTime - startTime)
        } catch (e: InvalidConfigurationException) {
            throw RuntimeException("Error creating solver context", e)
        }
    }

    protected fun advanceSolverTime(time: Long) {
        solverTime += time
    }

    /**
     * Finds the corresponding SolverContextFactory.Solvers enum value for the given SMTSolverTypes enum value.
     *
     * @param type the type of SMT solver to find the corresponding enum value for.
     * @return the corresponding SolverContextFactory.Solvers enum value.
     */
    fun findSolverType(type: SMTSolverTypes): Solvers {
        return when (type) {
            SMTSolverTypes.OPENSMT -> Solvers.OPENSMT
            SMTSolverTypes.MATHSAT5 -> Solvers.MATHSAT5
            SMTSolverTypes.SMTINTERPOL -> Solvers.SMTINTERPOL
            SMTSolverTypes.Z3 -> Solvers.Z3
            SMTSolverTypes.PRINCESS -> Solvers.PRINCESS
            SMTSolverTypes.BOOLECTOR -> Solvers.BOOLECTOR
            SMTSolverTypes.CVC4 -> Solvers.CVC4
            SMTSolverTypes.CVC5 -> Solvers.CVC5
            SMTSolverTypes.YICES2 -> Solvers.YICES2
            SMTSolverTypes.OFF -> throw IllegalArgumentException("Solver type cannot be OFF")
        }
    }

    abstract fun size(): Int

    /**
     * Solves the given symbolic formula and returns the result.
     *
     * @param operation the symbolic operation containing the formula to solve.
     * @return true if the formula is satisfiable, false otherwise.
     */
    fun solveSymbolicFormula(operation: JmcBooleanFormula): Boolean {
        return solve(operation.formula)
    }

    /**
     * Dissolves the given symbolic formula and returns the result.
     *
     * @param operation the symbolic operation containing the formula to dissolve.
     * @return true if the formula is unsatisfiable, false otherwise.
     */
    fun disSolveSymbolicFormula(operation: JmcBooleanFormula): Boolean {
        return solve(negateFormula(operation))
    }

    /**
     * Solves the given boolean formula and returns the result.
     *
     *
     * This method creates a new prover environment, adds the boolean formula as a constraint, and checks if the formula
     * is satisfiable. If the formula is satisfiable, the model generated by the solver is stored in the model property.
     * The method returns true if the formula is satisfiable, and false otherwise.
     *
     *
     * @param formula the boolean formula to solve.
     * @return true if the formula is satisfiable, false otherwise.
     */
    protected abstract fun solve(formula: BooleanFormula): Boolean

    /**
     * Negates the given boolean formula and returns the result.
     *
     * @param formula the boolean formula to negate.
     * @return the negated boolean formula.
     */
    fun negateFormula(formula: JmcBooleanFormula): BooleanFormula {
        return bmgr!!.not(formula.formula)
    }

    fun getSymIntVariableMap(): Map<String, SymIntVariable> {
        return symIntVariableMap
    }

    /**
     * Returns the symbolic integer variable with the given name.
     *
     *
     * This method checks if the symbolic integer variable with the given name already exists in the symIntVariableMap.
     * If the variable exists, it returns the existing variable. Otherwise, it creates a new symbolic integer variable
     * with the given name, stores it in the symIntVariableMap, and returns the new variable.
     *
     *
     * @param name the name of the symbolic integer variable to retrieve.
     * @return the symbolic integer variable with the given name.
     */
    fun getSymIntVariable(name: String): SymIntVariable? {
        if (symIntVariableMap.containsKey(name)) {
            //Returning existing SymIntVariable
            return symIntVariableMap[name]
        } else {
            //Creating new SymIntVariable
            val symInt = imgr!!.makeVariable(name)
            val variable = SymIntVariable(symInt)
            symIntVariableMap[name] = variable
            return variable
        }
    }

    fun getSymIntVarValue(name: String): Int {
        if (symIntVariableMap.containsKey(name)) {
            return symIntVariableMap[name].getValue()
        } else {
            throw RuntimeException("Symbolic integer variable not found: $name")
        }
    }

    /**
     * Returns the symbolic boolean variable with the given name.
     *
     *
     * This method checks if the symbolic boolean variable with the given name already exists in the symBoolVariableMap.
     * If the variable exists, it returns the existing variable. Otherwise, it creates a new symbolic boolean variable
     * with the given name, stores it in the symBoolVariableMap, and returns the new variable.
     *
     *
     * @param name the name of the symbolic boolean variable to retrieve.
     * @return the symbolic boolean variable with the given name.
     */
    fun getSymBoolVariable(name: String): SymBoolVariable? {
        if (symBoolVariableMap.containsKey(name)) {
            //Return an existing SymBoolVariable
            return symBoolVariableMap[name]
        } else {
            //Create a new SymBoolVariable
            val symBool = bmgr!!.makeVariable(name)
            val variable = SymBoolVariable(symBool)
            symBoolVariableMap[name] = variable
            return variable
        }
    }

    fun getSymBoolVarValue(name: String?): Boolean {
        if (symBoolVariableMap.containsKey(name)) {
            return symBoolVariableMap[name].getValue()
        } else {
            throw RuntimeException("Symbolic boolean variable not found: $name")
        }
    }

    fun setFreshProverFlag(resetProver: Boolean) {
        this.isFreshProver = resetProver
    }

    fun addFormula(formula: JmcBooleanFormula) {
        push(formula)
    }

    fun addNegatedFormula(formula: JmcBooleanFormula) {
        push(negateFormula(formula))
    }

    protected abstract fun pop()

    protected abstract fun push()

    protected abstract fun push(formula: BooleanFormula)

    protected abstract fun push(operation: JmcBooleanFormula)

    abstract fun computeNewSymbolicOperation(symbolicOperation: JmcBooleanFormula): SolverResult

    abstract fun computeNewSymAssumeOperation(symbolicOperation: JmcBooleanFormula): Boolean

    abstract fun computeGuidedSymAssumeOperation(symbolicOperation: JmcBooleanFormula)

    abstract fun computeNewSymAssertOperation(symbolicOperation: JmcBooleanFormula?): Boolean

    abstract fun solveAndUpdateModel()

    abstract fun createNewProver(): ProverState

    abstract fun setProver(proverState: ProverState, proverId: Int)

    abstract val proverId: Int

    abstract fun resetProver(prover: ProverEnvironment)
}
